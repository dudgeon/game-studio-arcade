/**
 * GLYPHS[code - 32] is an array of GLYPH_H row bitmasks; bit 4 is the
 * leftmost column.
 * @type {readonly Uint8Array[]}
 */
export const GLYPHS = Object.freeze(
  SOURCE.map((src) => {
    const rows = new Uint8Array(GLYPH_H);
    src
      .split(" ")
      .filter(Boolean)
      .forEach((row, y) => {
        let bits = 0;
        for (let x = 0; x < GLYPH_W; x++) if (row[x] === "#") bits |= 1 << (GLYPH_W - 1 - x);
        rows[y] = bits;
      });
    return rows;
  }),
);

/** Glyph rows for a character; unknown characters draw as "?". */
export function glyph(ch) {
  const code = ch.charCodeAt(0);
  return GLYPHS[code >= 32 && code <= 126 ? code - 32 : 31];
}

/** Width in pixels of the widest line of `s` at `scale`. */
export function textWidth(s, scale = 1) {
  const lines = String(s).split("\n");
  const longest = Math.max(...lines.map((l) => l.length));
  return longest === 0 ? 0 : (longest * ADVANCE - 1) * scale;
}
